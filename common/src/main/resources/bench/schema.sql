-- Benchmark schema (SPEC.md section 2). Created by bench.common.dataset.Database, never by a framework.
DROP TABLE IF EXISTS order_line;
DROP TABLE IF EXISTS purchase_order;
DROP TABLE IF EXISTS book;
DROP TABLE IF EXISTS author;
DROP TABLE IF EXISTS stock_item;
DROP TABLE IF EXISTS bench_meta;

CREATE TABLE author (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    country CHAR(2) NOT NULL
);

CREATE TABLE book (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id BIGINT NOT NULL REFERENCES author (id),
    title VARCHAR(200) NOT NULL,
    isbn VARCHAR(32) NOT NULL UNIQUE,
    pages INT NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    published_on DATE NOT NULL
);

CREATE INDEX book_author_id_idx ON book (author_id);

CREATE TABLE purchase_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference UUID NOT NULL UNIQUE,
    customer VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX purchase_order_customer_idx ON purchase_order (customer);

CREATE TABLE order_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES purchase_order (id),
    line_no INT NOT NULL,
    product VARCHAR(100) NOT NULL,
    quantity INT NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    UNIQUE (order_id, line_no)
);

CREATE TABLE stock_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(32) NOT NULL UNIQUE,
    quantity INT NOT NULL,
    version INT NOT NULL
);

CREATE TABLE bench_meta (
    name VARCHAR(50) PRIMARY KEY,
    value VARCHAR(200) NOT NULL
);
